	/**
	 * Normalise the compact lesson tuples into repeater rows.
	 *
	 * @param array<int, array{0: string, 1: string[]}> $rows Title/bullets pairs.
	 * @return array<int, array<string, string>>
	 */
	private static function lesson_rows( array $rows ): array {
		return array_map(
			static fn( array $row ): array => array(
				'title'   => $row[0],
				'bullets' => implode( "\n", $row[1] ),
			),
			$rows
		);
	}

